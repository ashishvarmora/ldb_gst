import type { Metadata } from "next";
import Link from "next/link";

import { Bullets, Callout, ContentPage, Section } from "@/components/ContentPage";
import { PublicShell, publicHeaderAction, publicSettings } from "@/components/SiteFooter";

export async function generateMetadata(): Promise<Metadata> {
  const { brandName } = await publicSettings();
  return {
    title: `Where the data comes from — ${brandName}`,
    description:
      "A plain declaration of our data sources, what the records can show, what they cannot, and the limits every reader should assume.",
  };
}

/**
 * The data declaration.
 *
 * Its own page, and linked from the footer, About, Support and the Terms,
 * because it is the single most consequential thing a reader can misunderstand
 * about this product. Somebody who believes they are watching live GPS will
 * read a four-hour gap as a stopped lorry and act on it.
 *
 * Written to claim nothing that is not true. It does not say the platform is
 * authorised, endorsed, certified or partnered - those are the claims that turn
 * a data disclosure into a misrepresentation - and it says outright that it is
 * none of those things.
 */
export default async function DataSourcesPage() {
  const [{ brandName }, action] = await Promise.all([publicSettings(), publicHeaderAction()]);

  return (
    <PublicShell action={action} mainClassName="flex-1">
      <ContentPage
        title="Where the data comes from"
        updated="1 September 2026"
        intro={`${brandName} does not observe vehicles itself. Everything shown is derived from movement records generated by India's logistics and tolling infrastructure. This page states plainly what that means for what you are looking at.`}
      >
        <Callout tone="warn" title="Read this before you rely on anything here">
          These records show where a vehicle was <em>recorded</em>, not where it is. They can be
          delayed, incomplete, or absent entirely for journeys that pass no reading point. An
          absence of records is not evidence that a vehicle did not travel.
        </Callout>

        <Section id="origin" title="1. Origin of the records">
          <p>
            When a commercial vehicle passes a tolled highway plaza, its passage is captured
            electronically at the gantry. Those readings are consolidated into India&rsquo;s national
            logistics data infrastructure — the Logistics Data Bank programme and the Unified
            Logistics Interface Platform, both operated by NICDC Logistics Data Services Limited, a
            joint venture involving the Government of India and NEC Corporation.
          </p>
          <p>
            {brandName} obtains vehicle movement records from that infrastructure and presents them
            against the registration number you enquire about. We do not create, alter, enrich or
            re-interpret the underlying readings. What you see is what was reported to us, arranged
            into chronological order.
          </p>
        </Section>

        <Section id="independence" title="2. We are not a government service">
          <Callout>
            {brandName} is an independent, privately operated platform. It is{" "}
            <strong>not</strong> operated by, affiliated with, endorsed by, certified by, or acting
            on behalf of any government department, ministry, statutory body, NICDC Logistics Data
            Services Limited, the Logistics Data Bank programme, or the Unified Logistics Interface
            Platform.
          </Callout>
          <p>
            References to those programmes on this page describe the origin of the data and nothing
            more. No endorsement or official status should be inferred from them, and nothing on
            this platform is an official record or a certified extract.
          </p>
        </Section>

        <Section id="limits" title="3. What the records cannot tell you">
          <p>
            The limits below are properties of how the data is generated. They are not faults in
            this platform and cannot be fixed by it.
          </p>
          <Bullets
            items={[
              <>
                <strong className="text-ink">Coverage is not universal.</strong> A vehicle is only
                visible where a reading point exists. Journeys on untolled roads, state highways and
                local routes may generate no records at all.
              </>,
              <>
                <strong className="text-ink">It is not continuous.</strong> Between two reading
                points there is no information. A long gap may mean a halt, a route without
                gantries, a reading that failed, or a device that was not detected.
              </>,
              <>
                <strong className="text-ink">It is not real time.</strong> A reading reaches us
                after it has been captured and passed on. Timestamps describe when a crossing was
                recorded, not when you are seeing it.
              </>,
              <>
                <strong className="text-ink">It identifies a vehicle, not a person.</strong> Nothing
                here establishes who was driving, who owned the cargo, or who was travelling.
              </>,
              <>
                <strong className="text-ink">It can be wrong.</strong> Misreads, duplicate reports
                and missing entries occur. We fold obvious duplicates together, but we cannot detect
                a reading that was never made.
              </>,
            ]}
          />
        </Section>

        <Section id="use" title="4. How findings should be used">
          <p>
            Information from {brandName} is provided for lawful informational purposes. It is
            suitable as a lead, a cross-check, or an operational aid. It is{" "}
            <strong className="text-ink">not</strong> suitable as sole or conclusive proof of the
            movement, location, delay or conduct of any vehicle, consignment or person.
          </p>
          <p>
            Anyone intending to rely on these records in a legal, regulatory, disciplinary,
            contractual or enforcement context must independently verify them through the
            appropriate official channel. Any decision taken on the basis of what is shown here
            remains the decision and the responsibility of the person taking it.
          </p>
        </Section>

        <Section id="lawful" title="5. Your obligation when you enquire">
          <p>
            You may only enquire about a vehicle where you have a lawful basis to do so — for
            example, it is yours, it is operated under your contract, or you are exercising a
            function you are legally authorised to exercise. You must not use {brandName} to
            monitor an individual, or for surveillance, harassment, or any purpose prohibited by
            law.
          </p>
          <p>
            Every enquiry is recorded against the account that made it, together with the vehicle
            number and the time. Those records are retained and may be disclosed where we are
            lawfully required to do so. Full obligations are in the{" "}
            <Link href="/terms" className="font-medium text-brand-500 hover:underline">
              terms of use
            </Link>
            .
          </p>
        </Section>

        <Section id="upstream" title="6. Availability and change">
          <p>
            We depend on upstream systems we do not control. Coverage, data fields, refresh
            behaviour and availability may change, be interrupted, or be withdrawn without notice to
            us, and therefore without notice to you. Where that materially affects what this
            platform can do, we will say so on this page.
          </p>
        </Section>

        <Section id="corrections" title="7. Reporting something that looks wrong">
          <p>
            If a record appears incorrect, tell us through{" "}
            <Link href="/contact" className="font-medium text-brand-500 hover:underline">
              the contact page
            </Link>
            . Be aware of what we can and cannot do: we can check that we have represented the
            reading we received faithfully, and correct our own handling of it. We cannot amend the
            underlying reading, because it is not ours.
          </p>
        </Section>
      </ContentPage>
    </PublicShell>
  );
}
