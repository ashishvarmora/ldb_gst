const BY_NAME = new Map(PLACES.map((place) => [key(place.name), place]));

/**
 * The place a typed or picked name refers to, or null. Case and spacing are
 * forgiven; anything else has to match a name in the list.
 */
export function findPlace(name: string): Place | null {
  return BY_NAME.get(key(name)) ?? null;
}
